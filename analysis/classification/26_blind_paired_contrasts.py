# 2. INPUT VALIDATION AND METRICS
# =============================================================================

def require_file(path: Path, description: str) -> None:
    if not path.exists():
        raise FileNotFoundError(f"{description} was not found:\n{path}")


def validate_predictions(frame: pd.DataFrame) -> pd.DataFrame:
    required = {
        CODE_COLUMN,
        TARGET_COLUMN,
        FAMILY_COLUMN,
        PROBABILITY_COLUMN,
    }
    missing = sorted(required - set(frame.columns))
    if missing:
        raise ValueError(
            f"{PREDICTIONS_PATH.name} is missing required columns: {missing}"
        )

    checked = frame.copy()
    checked[CODE_COLUMN] = checked[CODE_COLUMN].astype("string").str.strip()
    checked[FAMILY_COLUMN] = checked[FAMILY_COLUMN].astype("string").str.strip()
    checked[TARGET_COLUMN] = pd.to_numeric(
        checked[TARGET_COLUMN], errors="coerce"
    )
    checked[PROBABILITY_COLUMN] = pd.to_numeric(
        checked[PROBABILITY_COLUMN], errors="coerce"
    )

    if checked[CODE_COLUMN].isna().any() or checked[CODE_COLUMN].eq("").any():
        raise ValueError("Blind prediction table contains missing Code values.")
    if checked[FAMILY_COLUMN].isna().any() or checked[FAMILY_COLUMN].eq("").any():
        raise ValueError("Blind prediction table contains missing family labels.")
    if checked[TARGET_COLUMN].isna().any():
        raise ValueError("Blind prediction table contains missing activity labels.")
    if set(checked[TARGET_COLUMN].astype(int).unique()) != {0, 1}:
        raise ValueError("Blind activity must contain both binary classes 0 and 1.")
    checked[TARGET_COLUMN] = checked[TARGET_COLUMN].astype(int)

    if (
        checked[PROBABILITY_COLUMN].isna().any()
        or not np.isfinite(checked[PROBABILITY_COLUMN]).all()
        or (checked[PROBABILITY_COLUMN] < 0.0).any()
        or (checked[PROBABILITY_COLUMN] > 1.0).any()
    ):
        raise ValueError("probability_nades must contain finite values in [0, 1].")

    duplicate = checked.duplicated(
        subset=[CODE_COLUMN, FAMILY_COLUMN], keep=False
    )
    if duplicate.any():
        examples = checked.loc[
            duplicate, [CODE_COLUMN, FAMILY_COLUMN]
        ].head(10)
        raise ValueError(
            "Each blind Code/family pair must have one frozen probability.\n"
            f"Duplicated examples:\n{examples.to_string(index=False)}"
        )

    return checked


def metric_values(y_true: np.ndarray, probability_nades: np.ndarray) -> dict[str, float]:
    """Ranking and frozen-threshold readouts for a binary blind sample."""
    prediction = (probability_nades >= THRESHOLD).astype(int)
    return {
        "roc_auc_nades": float(roc_auc_score(y_true, probability_nades)),
        "ap_nades": float(average_precision_score(y_true, probability_nades)),
        "ap_non_nades": float(
            average_precision_score(1 - y_true, 1.0 - probability_nades)
        ),
        "balanced_accuracy_tau050": float(
            balanced_accuracy_score(y_true, prediction)
        ),
        "mcc_tau050": float(matthews_corrcoef(y_true, prediction)),
    }


def make_prediction_matrix(
    predictions: pd.DataFrame,
) -> tuple[pd.DataFrame, list[str]]:
    """Align all family probability vectors against the same blind mixtures."""
    available_families = set(predictions[FAMILY_COLUMN])
    if REFERENCE_FAMILY not in available_families:
        raise ValueError(
            f"Reference family {REFERENCE_FAMILY!r} is not present. "
            f"Available: {sorted(available_families)}"
        )

    ordered_families = [
        family for family in FAMILY_ORDER if family in available_families
    ]
    ordered_families.extend(
        sorted(available_families - set(ordered_families))
    )

    n_codes = predictions[CODE_COLUMN].nunique()
    expected = n_codes * len(ordered_families)
    if len(predictions) != expected:
        coverage = predictions.groupby(CODE_COLUMN)[FAMILY_COLUMN].nunique()
        incomplete = coverage.loc[coverage != len(ordered_families)].head(10)
        raise ValueError(
            "Not every blind mixture has all family predictions. "
            f"Examples:\n{incomplete.to_string()}"
        )

    metadata = predictions[[CODE_COLUMN, TARGET_COLUMN]].drop_duplicates()
    if len(metadata) != n_codes:
        raise ValueError("The blind activity label differs across families for a Code.")

    probability_matrix = predictions.pivot(
        index=CODE_COLUMN,
        columns=FAMILY_COLUMN,
        values=PROBABILITY_COLUMN,
    )
    matrix = metadata.set_index(CODE_COLUMN).join(
        probability_matrix, how="inner"
    ).sort_index()
    if matrix[ordered_families].isna().any().any():
        raise ValueError("At least one aligned family-probability cell is missing.")
    return matrix, ordered_families


def stratified_bootstrap_indices(
    y_true: np.ndarray,
    rng: np.random.Generator,
) -> np.ndarray:
    """Resample each class separately, guaranteeing valid ROC/AP draws."""
    positive = np.flatnonzero(y_true == 1)
    negative = np.flatnonzero(y_true == 0)
    return np.concatenate([
        rng.choice(positive, size=len(positive), replace=True),
        rng.choice(negative, size=len(negative), replace=True),
    ])


def conclusion(ci_low: float, ci_high: float) -> str:
    if ci_low > 0.0:
        return "Reference family better"
    if ci_high < 0.0:
        return "Comparator family better"
    return "Inconclusive at 95% bootstrap interval"


# =============================================================================
# 3. PAIRED STRATIFIED-BOOTSTRAP CONTRASTS
# =============================================================================

def paired_bootstrap_contrasts(
    matrix: pd.DataFrame,
    families: list[str],
) -> pd.DataFrame:
    """Compare the frozen reference family with every other family."""
    y_true = matrix[TARGET_COLUMN].to_numpy(dtype=int)
    reference_probability = matrix[REFERENCE_FAMILY].to_numpy(dtype=float)
    reference_metrics = metric_values(y_true, reference_probability)

    rows: list[dict[str, object]] = []
    metric_order = list(reference_metrics)
    for comparator_number, comparator in enumerate(families):
        if comparator == REFERENCE_FAMILY:
            continue

        comparator_probability = matrix[comparator].to_numpy(dtype=float)
        comparator_metrics = metric_values(y_true, comparator_probability)
        point_delta = {
            metric: reference_metrics[metric] - comparator_metrics[metric]
            for metric in metric_order
        }
        draws = {metric: [] for metric in metric_order}

        # New reproducible stream per contrast; within every draw, both family
        # predictions are evaluated on exactly the same resampled blind systems.
        contrast_rng = np.random.default_rng(SEED + comparator_number + 1)
        for _ in range(N_BOOTSTRAP):
            sampled = stratified_bootstrap_indices(y_true, contrast_rng)
            sampled_y = y_true[sampled]
            ref_draw = metric_values(
                sampled_y, reference_probability[sampled]
            )
            comp_draw = metric_values(
                sampled_y, comparator_probability[sampled]
            )
            for metric in metric_order:
                draws[metric].append(ref_draw[metric] - comp_draw[metric])

        for metric in metric_order:
            values = np.asarray(draws[metric], dtype=float)
            valid = values[np.isfinite(values)]
            ci_low = float(np.percentile(valid, 2.5)) if len(valid) else np.nan
            ci_high = float(np.percentile(valid, 97.5)) if len(valid) else np.nan
            rows.append({
                "reference_family": REFERENCE_FAMILY,
                "reference_family_label": FAMILY_LABELS.get(
                    REFERENCE_FAMILY, REFERENCE_FAMILY
                ),
                "comparator_family": comparator,
                "comparator_family_label": FAMILY_LABELS.get(
                    comparator, comparator
                ),
                "comparison": (
                    f"{FAMILY_LABELS.get(REFERENCE_FAMILY, REFERENCE_FAMILY)} "
                    f"minus {FAMILY_LABELS.get(comparator, comparator)}"
                ),
                "metric": metric,
                "reference_point_value": reference_metrics[metric],
                "comparator_point_value": comparator_metrics[metric],
                "point_estimate": point_delta[metric],
                "bootstrap_ci_low": ci_low,
                "bootstrap_ci_high": ci_high,
                "positive_favors": FAMILY_LABELS.get(
                    REFERENCE_FAMILY, REFERENCE_FAMILY
                ),
                "bootstrap_fraction_favoring_reference": (
                    float(np.mean(valid > 0.0)) if len(valid) else np.nan
                ),
                "conclusion": conclusion(ci_low, ci_high),
                "n_blind_systems": int(len(matrix)),
                "n_nades": int(np.sum(y_true == 1)),
                "n_non_nades": int(np.sum(y_true == 0)),
                "bootstrap_unit": "blind mixture; stratified by true class",
                "n_bootstrap_requested": N_BOOTSTRAP,
                "n_bootstrap_valid": int(len(valid)),
            })

    return pd.DataFrame(rows)


# =============================================================================
# 4. MAIN
# =============================================================================

def main() -> None:
    if N_BOOTSTRAP < 100:
        raise ValueError("N_BOOTSTRAP must be at least 100.")

    require_file(PREDICTIONS_PATH, "Frozen external-blind family predictions")
    predictions = validate_predictions(
        pd.read_csv(PREDICTIONS_PATH, low_memory=False)
    )
    matrix, families = make_prediction_matrix(predictions)
    contrasts = paired_bootstrap_contrasts(matrix, families)

    data_path('Classification_Family_Blind_Validation_RF').mkdir(parents=True, exist_ok=True)
    contrasts.to_csv(CONTRASTS_OUT, index=False)

    print("=" * 105)
    print("CLASSIFICATION FAMILY READOUT — PAIRED EXTERNAL-BLIND BOOTSTRAP")
    print("=" * 105)
    print(f"Blind mixtures              : {len(matrix)}")
    print(f"NADES / non-NADES           : {(matrix[TARGET_COLUMN] == 1).sum()} / {(matrix[TARGET_COLUMN] == 0).sum()}")
    print(f"Reference family            : {FAMILY_LABELS.get(REFERENCE_FAMILY, REFERENCE_FAMILY)}")
    print(f"Fixed RF threshold          : {THRESHOLD:.2f}")
    print(f"Stratified bootstrap draws  : {N_BOOTSTRAP}")
    print("Positive contrast = better reference family.\n")

    primary = contrasts.loc[
        contrasts["metric"] == "roc_auc_nades"
    ].copy()
    print("Primary paired ROC-AUC contrasts:")
    print(
        primary[
            [
                "comparator_family_label",
                "reference_point_value",
                "comparator_point_value",
                "point_estimate",
                "bootstrap_ci_low",
                "bootstrap_ci_high",
                "bootstrap_fraction_favoring_reference",
                "conclusion",
            ]
        ].to_string(
            index=False,
            float_format=lambda value: f"{value:.4f}",
        )
    )
    print(f"\nSaved:\n - {CONTRASTS_OUT}")
    print(
        "\nThis is post-hoc uncertainty reporting on frozen blind predictions only. "
        "Do not use it to alter the model or family design."
    )


if __name__ == "__main__":
    main()


