CONTRASTS_OUT = data_path('Classification_Family_Blind_Validation_RF/blind_family_paired_bootstrap_contrasts.csv')

CODE_COLUMN = "Code"
TARGET_COLUMN = "activity"
FAMILY_COLUMN = "family"
PROBABILITY_COLUMN = "probability_nades"

THRESHOLD = 0.50                 # frozen operational threshold
N_BOOTSTRAP = int(os.environ.get("N_BOOTSTRAP", "5000"))
SEED = 20260804

# The scientifically relevant default from the completed family experiment.
# Set REFERENCE_FAMILY in the environment to run an alternative *reporting*
# contrast without changing a model, e.g. REFERENCE_FAMILY=Weighted_mixture.
REFERENCE_FAMILY = os.environ.get("REFERENCE_FAMILY", "Component_B")

FAMILY_ORDER = [
    "Component_A",
    "Component_B",
    "Component_A_plus_B",
    "Weighted_mixture",
    "Arithmetic_mean",
    "AB_interactions",
]

FAMILY_LABELS = {
    "Component_A": "Component A",
    "Component_B": "Component B",
    "Component_A_plus_B": "A + B components",
    "Weighted_mixture": "Weighted mixture",
    "Arithmetic_mean": "Arithmetic mean",
    "AB_interactions": "AB interactions",
}


