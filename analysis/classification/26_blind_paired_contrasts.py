
"""
CLASSIFICATION FAMILY READOUT — PAIRED EXTERNAL-BLIND BOOTSTRAP
================================================================

Post-hoc uncertainty analysis for the frozen family-level blind validation.

This script does NOT refit models, select descriptors, alter K=8, alter the
RF threshold, or reread the labelled training table.  It only reads the
already saved blind probabilities generated by:

    Classification_Family_Blind_Validation_RF.py

The default contrast is Component_B versus every other descriptor family.
The comparison is paired: each stratified bootstrap draw resamples the same
blind NADES and non-NADES mixtures for both families.  Therefore the output
quantifies uncertainty in a family *difference*, not uncertainty in two
independent AUC estimates.

Positive deltas always favour the reference family (default: Component B):

    delta_roc_auc_nades              = ROC-AUC(reference) - ROC-AUC(other)
    delta_ap_nades                   = AP_NADES(reference) - AP_NADES(other)
    delta_ap_non_nades               = AP_non-NADES(reference) - AP_non-NADES(other)
    delta_balanced_accuracy_tau050   = BA(reference) - BA(other)
    delta_mcc_tau050                 = MCC(reference) - MCC(other)

The blind labels have already been consumed by the preceding frozen external
validation.  This script is permitted post-hoc reporting only: its results
must not be used to change the descriptor budget, family definitions, model,
threshold, or claimed winner after the fact.

Input:
    Classification_Family_Blind_Validation_RF/blind_family_predictions.csv

Output:
    Classification_Family_Blind_Validation_RF/
        blind_family_paired_bootstrap_contrasts.csv
"""

